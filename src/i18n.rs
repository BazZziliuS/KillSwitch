//! Every user-facing string. Each language fills the same struct, so a missing translation cannot compile.

use crate::protection::rules::Reason;
use serde::{Deserialize, Serialize};
use windows::Win32::Globalization::GetUserDefaultUILanguage;

const LANG_RUSSIAN: u16 = 0x19;
const PRIMARY_LANGUAGE_MASK: u16 = 0x3FF;

#[derive(Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Language {
    #[serde(rename = "en")]
    English,
    #[serde(rename = "ru")]
    Russian,
}

impl Language {
    pub const ALL: [Language; 2] = [Language::English, Language::Russian];

    pub fn native_name(self) -> &'static str {
        match self {
            Language::English => "English",
            Language::Russian => "Русский",
        }
    }

    fn system() -> Self {
        if unsafe { GetUserDefaultUILanguage() } & PRIMARY_LANGUAGE_MASK == LANG_RUSSIAN {
            Language::Russian
        } else {
            Language::English
        }
    }
}

/// `None` follows the Windows display language.
pub fn strings(choice: Option<Language>) -> &'static Strings {
    match choice.unwrap_or_else(Language::system) {
        Language::English => &ENGLISH,
        Language::Russian => &RUSSIAN,
    }
}

